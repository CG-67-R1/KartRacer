#!/usr/bin/env node
/**
 * Sync the setup engine into both Expo apps.
 *
 * Copies tools/setup-engine/src -> app/src/lib/setupEngine and
 * android-app/src/lib/setupEngine, plus the four kb/rules JSON files the
 * engine reads, and rewrites src/rules/load.ts to import the local copies.
 * Test files are excluded (vitest stays in tools/setup-engine).
 *
 * The engine remains developed + tested in tools/setup-engine (npm test).
 * Never edit app/src/lib/setupEngine by hand — it is overwritten here.
 *
 * Usage: node scripts/sync-setup-engine.mjs [--check]
 *   --check  exit 1 if the app copies are stale (CI / preflight gate)
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const repo = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const engineSrc = path.join(repo, "tools", "setup-engine", "src");
const rulesSrc = path.join(repo, "kb", "rules");
const RULE_FILES = ["handling.json", "pressure.json", "tyre-temps.json", "wet-weather.json"];
/** kb/data files imported by calculators; copied to <target>/kbdata/. */
const DATA_FILES = ["jetting-rad.json"];
const TARGETS = [
  path.join(repo, "app", "src", "lib", "setupEngine"),
  path.join(repo, "android-app", "src", "lib", "setupEngine"),
];
const HEADER = "// AUTO-GENERATED by scripts/sync-setup-engine.mjs — do not edit. Source: tools/setup-engine/src\n";

const checkMode = process.argv.includes("--check");

function listSourceFiles(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listSourceFiles(p, base));
    else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts")) {
      out.push(path.relative(base, p));
    }
  }
  return out;
}

function transform(rel, text) {
  let body = text;
  const posix = rel.replace(/\\/g, "/");
  if (posix === "rules/load.ts") {
    body = body.replace(/from "(?:\.\.\/)+kb\/rules\/(.+?\.json)"/g, 'from "./$1"');
  } else {
    // Calculators import kb/data JSON (e.g. jetting.ts). Depth from file location to <root>/kbdata/.
    const depth = posix.split("/").length - 1;
    const prefix = depth > 0 ? "../".repeat(depth) : "./";
    body = body.replace(/from "(?:\.\.\/)+kb\/data\/(.+?\.json)"/g, `from "${prefix}kbdata/$1"`);
  }
  if (/from "(?:\.\.\/)+kb\//.test(body)) {
    throw new Error(`${rel} still references ../kb after rewrite — extend the sync script`);
  }
  return HEADER + body;
}

function hashText(t) {
  return createHash("sha1").update(t.replace(/\r\n/g, "\n")).digest("hex");
}

const files = listSourceFiles(engineSrc);
if (files.length === 0) {
  console.error("No engine sources found at", engineSrc);
  process.exit(1);
}

let wrote = 0;
let stale = 0;
for (const target of TARGETS) {
  if (!fs.existsSync(path.dirname(path.dirname(target)))) {
    console.warn(`skip (missing app tree): ${target}`);
    continue;
  }
  for (const rel of files) {
    const srcText = fs.readFileSync(path.join(engineSrc, rel), "utf8");
    const outText = transform(rel, srcText);
    const dest = path.join(target, rel);
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
    if (current !== null && hashText(current) === hashText(outText)) continue;
    if (checkMode) {
      console.error(`STALE: ${path.relative(repo, dest)}`);
      stale++;
      continue;
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, outText);
    wrote++;
  }
  for (const ruleFile of RULE_FILES) {
    const srcPath = path.join(rulesSrc, ruleFile);
    if (!fs.existsSync(srcPath)) {
      console.error(`Missing rules file: ${srcPath}`);
      process.exit(1);
    }
    const srcText = fs.readFileSync(srcPath, "utf8");
    const dest = path.join(target, "rules", ruleFile);
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
    if (current !== null && hashText(current) === hashText(srcText)) continue;
    if (checkMode) {
      console.error(`STALE: ${path.relative(repo, dest)}`);
      stale++;
      continue;
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, srcText);
    wrote++;
  }
  for (const dataFile of DATA_FILES) {
    const srcPath = path.join(repo, "kb", "data", dataFile);
    if (!fs.existsSync(srcPath)) {
      console.error(`Missing kb/data file: ${srcPath}`);
      process.exit(1);
    }
    const srcText = fs.readFileSync(srcPath, "utf8");
    const dest = path.join(target, "kbdata", dataFile);
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
    if (current !== null && hashText(current) === hashText(srcText)) continue;
    if (checkMode) {
      console.error(`STALE: ${path.relative(repo, dest)}`);
      stale++;
      continue;
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, srcText);
    wrote++;
  }
}

if (checkMode) {
  if (stale > 0) {
    console.error(`\n${stale} stale file(s). Run: node scripts/sync-setup-engine.mjs`);
    process.exit(1);
  }
  console.log("setup-engine app copies are in sync.");
} else {
  console.log(`Synced setup engine: ${wrote} file(s) written across ${TARGETS.length} target(s).`);
  console.log("Import in app code as: import { diagnoseDriving } from '../lib/setupEngine';");
}
